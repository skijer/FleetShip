"""Extracts the enemy spawn tables of Ship (OoT) and 2Ship (MM) from their .o2r archives.

Writes EnemySpawns.inc and EnemySpawns.json next to each game's randomizer static data.
Master Quest dungeon rows (ROW_MQ) follow the vanilla ones, so vanilla row indices stay stable.
Usage: python extract_enemy_spawns.py [oot] [mm]
"""

