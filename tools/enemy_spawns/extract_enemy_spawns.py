class GameExtractor:
    def __init__(self, config, archive_path, scene_directories, row_flags=0):
        self.config = config
        self.archive = ResourceArchive(archive_path)
        self.scene_directories = scene_directories
        self.row_flags = row_flags
        self.dialect = SceneDialect(config.is_majoras_mask)
        self.actors_by_id = {actor.actor_id: actor for actor in read_actor_table(
            config.actor_table, config.actors_directory)}
        self.scenes = read_scene_table(config.scene_table)
        self.entrances = self.read_entrances()
        self.geometry_cache = {}

    def read_entrances(self):
        if self.config.is_majoras_mask:
            return read_mm_entrances(self.config.source_root / "src/code/z_scene_table.c", self.scenes)
        return read_oot_entrances(self.config.source_root / "include/tables/entrance_table.h", self.scenes)

    def load_header(self, resource_name):
        return parse_scene_header(self.archive.read(resource_name), self.dialect)

    def find_scene_resource(self, directory_name):
        for base in self.scene_directories:
            resource_name = f"{base}/{directory_name}/{directory_name}"
            if self.archive.contains(resource_name):
                return resource_name
        return None

    def load_setups(self, main_resource):
        main_header = self.load_header(main_resource)
        setups = [main_header]
        for alternate in main_header.alternate_headers or []:
            valid = alternate and self.archive.contains(alternate)
            setups.append(self.load_header(alternate) if valid else None)
        return setups

    def extract(self):
        rows = []
        scene_summaries = []
        for scene in self.scenes:
            main_resource = self.find_scene_resource(scene.directory_name)
            if main_resource is None:
                continue
            scene_rows, summary = self.extract_scene(scene, main_resource)
            rows.extend(scene_rows)
            scene_summaries.append(summary)
        return rows, scene_summaries

    def extract_scene(self, scene, main_resource):
        scene_setups = self.load_setups(main_resource)
        main_header = scene_setups[0]
        main_geometry = self.load_geometry(main_header)
        water_rooms = {box.room for box in main_geometry.water_boxes}
        room_setups = [self.load_setups(room) for room in main_header.rooms]
        rows = []
        clear_rooms = set()
        for room_index, setups in enumerate(room_setups):
            for setup_index, room_header in enumerate(setups):
                if room_header is None:
                    continue
                door_rooms = self.find_door_clear_rooms(scene_setups, setup_index)
                flags = self.room_flags(room_index, room_header, door_rooms, water_rooms)
                geometry = self.setup_geometry(scene_setups, setup_index, main_geometry)
                rows.extend(self.extract_room(scene, setup_index, room_index, room_header, flags, geometry))
                if flags & CLEAR_TRIGGER:
                    clear_rooms.add(room_index)
        summary = self.summarize_scene(scene, main_header, water_rooms, clear_rooms)
        return rows, summary

    def find_door_clear_rooms(self, scene_setups, setup_index):
        header = scene_setups[setup_index] if setup_index < len(scene_setups) else None
        transitions = (header and header.transition_actors) or scene_setups[0].transition_actors or []
        rooms = set()
        for transition in transitions:
            actor = self.find_actor(transition.actor_id)
            if actor and actor.enum_name == "ACTOR_DOOR_SHUTTER":
                rooms.update(self.config.clear_rooms_of_transition(transition))
        return rooms

    def load_geometry(self, header):
        if header is None or not header.collision_path:
            return None
        path = header.collision_path
        if path not in self.geometry_cache:
            self.geometry_cache[path] = read_collision(self.archive.read(path))
        return self.geometry_cache[path]

    def setup_geometry(self, scene_setups, setup_index, main_geometry):
        header = scene_setups[setup_index] if setup_index < len(scene_setups) else None
        return self.load_geometry(header) or main_geometry

    def room_flags(self, room_index, room_header, door_rooms, water_rooms):
        flags = self.row_flags
        waits_for_clear = room_index in door_rooms or any(
            self.actor_waits_for_clear(entry) for entry in room_header.actors or [])
        if waits_for_clear:
            flags |= CLEAR_TRIGGER
        if room_index in water_rooms or WATER_BOX_ALL_ROOMS in water_rooms:
            flags |= HAS_WATER
        return flags

    def find_actor(self, actor_id):
        return self.actors_by_id.get(actor_id & ACTOR_ID_MASK)

    def actor_waits_for_clear(self, entry):
        actor = self.find_actor(entry.actor_id)
        return actor is not None and self.config.waits_for_clear(actor.enum_name, entry.params)

    def extract_room(self, scene, setup_index, room_index, room_header, flags, geometry):
        rows = []
        for actor_index, entry in enumerate(room_header.actors or []):
            actor = self.find_actor(entry.actor_id)
            if actor is None or not self.is_enemy_row(actor, entry):
                continue
            row_flags = flags | (classify_water(entry.pos, room_index, geometry) if geometry else 0)
            rows.append(self.build_row(scene, setup_index, room_index, actor_index, actor, entry, row_flags))
        return rows

    def is_enemy_row(self, actor, entry):
        return actor.category in ENEMY_CATEGORIES or self.config.is_spawner(actor.enum_name, entry.params)

    def build_row(self, scene, setup_index, room_index, actor_index, actor, entry, flags):
        return {
            "sceneId": scene.scene_id,
            "setupIndex": setup_index,
            "roomIndex": room_index,
            "actorIndex": actor_index,
            "actorId": actor.actor_id,
            "params": to_signed_16(entry.params),
            "posX": entry.pos[0],
            "posY": entry.pos[1],
            "posZ": entry.pos[2],
            "rotY": to_signed_16(self.config.convert_rotation(entry.rot[1])),
            "roomFlags": flags,
            "actorName": actor.enum_name,
            "category": actor.category,
            "isSpawner": self.config.is_spawner(actor.enum_name, entry.params),
        }

    def summarize_scene(self, scene, main_header, water_rooms, clear_rooms):
        return {
            "sceneId": scene.scene_id,
            "name": scene.directory_name,
            "enumName": scene.enum_name,
            "roomCount": len(main_header.rooms),
            "clearRooms": sorted(clear_rooms),
            "waterRooms": sorted(water_rooms),
            "entrances": self.describe_entrances(scene, main_header),
        }

    def describe_entrances(self, scene, main_header):
        described = []
        for entrance in self.entrances:
            if entrance.scene_id != scene.scene_id:
                continue
            landing = self.find_landing(main_header, entrance.spawn)
            if landing is not None:
                described.append({"entrance": entrance.entrance, "spawn": entrance.spawn, **landing})
        return described

    def find_landing(self, main_header, spawn):
        entrance_list = main_header.entrances or []
        start_positions = main_header.start_positions or []
        if spawn >= len(entrance_list):
            return None
        start_index, room = entrance_list[spawn]
        if start_index >= len(start_positions):
            return None
        start = start_positions[start_index]
        return {
            "room": room,
            "startPosition": list(start.pos),
            "rotY": to_signed_16(self.config.convert_rotation(start.rot[1])),
        }


def format_inc(rows):
    lines = [GENERATED_HEADER]
    for row in rows:
        values = ", ".join(str(row[field]) for field in ROW_FIELDS)
        lines.append(f"{{ {values} }},")
    return "\n".join(lines) + "\n"


def extract_master_quest(config):
    if config.mq_archive_path is None:
        return [], []
    if not config.mq_archive_path.exists():
        print(f"{config.name}: no Master Quest archive at {config.mq_archive_path}, MQ rows skipped")
        return [], []
    return GameExtractor(config, config.mq_archive_path, MQ_SCENE_DIRECTORIES, ROW_MQ).extract()


def write_outputs(config, rows, scene_summaries, mq_scene_summaries):
    config.output_directory.mkdir(parents=True, exist_ok=True)
    (config.output_directory / "EnemySpawns.inc").write_text(format_inc(rows), encoding="utf-8")
    document = {
        "generatedBy": "tools/enemy_spawns/extract_enemy_spawns.py",
        "game": config.name,
        "rowFields": list(ROW_FIELDS),
        "rows": rows,
        "scenes": scene_summaries,
        "mqScenes": mq_scene_summaries,
    }
    (config.output_directory / "EnemySpawns.json").write_text(json.dumps(document, indent=1), encoding="utf-8")


def print_summary(config, rows, scene_summaries):
    clear_rooms = sum(len(scene["clearRooms"]) for scene in scene_summaries)
    clear_rows = sum(1 for row in rows if row["roomFlags"] & CLEAR_TRIGGER)
    water_rows = sum(1 for row in rows if row["roomFlags"] & HAS_WATER)
    submerged_rows = sum(1 for row in rows if row["roomFlags"] & ROW_SUBMERGED)
    surface_rows = sum(1 for row in rows if row["roomFlags"] & ROW_SURFACE)
    spawners = sum(1 for row in rows if row["isSpawner"])
    mq_rows = sum(1 for row in rows if row["roomFlags"] & ROW_MQ)
    entrances = sum(len(scene["entrances"]) for scene in scene_summaries)
    print(f"{config.name}: {len(rows)} rows ({mq_rows} MQ, {spawners} spawners, {water_rows} in water rooms, "
          f"{submerged_rows} submerged, {surface_rows} at the surface), "
          f"{len(scene_summaries)} scenes, {clear_rooms} CLEAR_TRIGGER rooms ({clear_rows} rows in them), "
          f"{entrances} entrances -> {config.output_directory}")


def main(arguments):
    selected = [config for config in (OOT, MM) if not arguments or config.name in arguments]
    for config in selected:
        rows, scene_summaries = GameExtractor(config, config.archive_path, config.scene_directories).extract()
        mq_rows, mq_scene_summaries = extract_master_quest(config)
        rows.extend(mq_rows)
        write_outputs(config, rows, scene_summaries, mq_scene_summaries)
        print_summary(config, rows, scene_summaries)


if __name__ == "__main__":
    main(sys.argv[1:])
