GITHUB = Path(__file__).resolve().parents[3]
CLEAR_TRIGGER = 1
HAS_WATER = 2
ROW_MQ = 32
MQ_SCENE_DIRECTORIES = ("scenes/mq",)
ENEMY_CATEGORIES = ("ACTORCAT_ENEMY", "ACTORCAT_BOSS")
ROW_FIELDS = ("sceneId", "setupIndex", "roomIndex", "actorIndex", "actorId", "params",
              "posX", "posY", "posZ", "rotY", "roomFlags")
ACTOR_ID_MASK = 0x1FFF
OOT_SPAWNER_ACTORS = frozenset({
    "ACTOR_EN_ENCOUNT1", "ACTOR_EN_ENCOUNT2", "ACTOR_EN_ANUBICE_TAG", "ACTOR_EN_BLKOBJ",
    "ACTOR_BG_HAKA_HUTA", "ACTOR_BG_HAKA_TUBO", "ACTOR_BG_MORI_BIGST",
})
MM_SPAWNER_ACTORS = frozenset({
    "ACTOR_EN_ENCOUNT1", "ACTOR_EN_ENCOUNT2", "ACTOR_EN_ENCOUNT3", "ACTOR_EN_ENCOUNT4",
})
GENERATED_HEADER ="// generated by tools/enemy_spawns/extract_enemy_spawns.py, do not edit"


def params_field(params, shift, mask):
    return (params >> shift) & mask


def oot_clear_rooms_of_transition(transition):
    door_type = params_field(transition.params, 6, 0xF)
    if door_type == 1:
        return [transition.back_room]
    return [transition.front_room] if door_type == 7 else []


def mm_clear_rooms_of_transition(transition):
    door_type = params_field(transition.params, 7, 7)
    if door_type == 1:
        return [transition.front_room]
    return [transition.back_room] if door_type in (6, 7) else []


def waits_for_clear_in_oot(enum_name, params):
    chest_type = params_field(params, 12, 0xF)
    return {
        "ACTOR_EN_BOX": chest_type in (1, 7),
        "ACTOR_BG_HIDAN_CURTAIN": chest_type in (0, 6),
        "ACTOR_BG_HIDAN_SYOKU": True,
        "ACTOR_BG_ICE_SHUTTER": (params & 0xFF) != 1,
        "ACTOR_BG_MORI_BIGST": True,
        "ACTOR_EN_BLKOBJ": True,
        "ACTOR_OBJ_ROOMTIMER": True,
        "ACTOR_BG_BDAN_OBJECTS": (params & 0xFF) == 0,
    }.get(enum_name, False)


def waits_for_clear_in_mm(enum_name, params):
    return {
        "ACTOR_EN_BOX": params_field(params, 12, 0xF) in (1, 7),
        "ACTOR_BG_HAKA_CURTAIN": True,
        "ACTOR_BG_HAKA_TOMB": True,
        "ACTOR_BG_IKANA_SHUTTER": params_field(params, 8, 1) == 1,
        "ACTOR_OBJ_ROOMTIMER": True,
    }.get(enum_name, False)


def is_spawner_in_oot(enum_name, params):
    if enum_name == "ACTOR_BG_HAKA":
        return params != 1
    if enum_name == "ACTOR_BG_BDAN_OBJECTS":
        return (params & 0xFF) == 0
    return enum_name in OOT_SPAWNER_ACTORS


def is_spawner_in_mm(enum_name, params):
    return enum_name in MM_SPAWNER_ACTORS


def convert_mm_rotation(rot_y):
    degrees = (rot_y >> 7) & 0x1FF
    return degrees * 0x10000 // 360


def to_signed_16(value):
    value &= 0xFFFF
    return value - 0x10000 if value >= 0x8000 else value


def keep_raw_rotation(rot_y):
    return rot_y


